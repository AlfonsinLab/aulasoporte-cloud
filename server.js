'use strict';
const express = require('express');
const path = require('node:path');
const { Pool } = require('pg');

const app = express();
const PORT = Number(process.env.PORT) || 3000;
if (!process.env.DATABASE_URL) {
  console.error('Falta DATABASE_URL. Configúrala como variable de entorno en Render.');
  process.exit(1);
}
const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10000, max: 5 });

app.disable('x-powered-by');
app.use(express.json({ limit: '12kb' }));
app.use(express.static(path.join(__dirname, 'public')));

const original = [
  [101, 'No se puede acceder al aula virtual', 'Software', 'Alta', 'Pendiente', 'Equipo de soporte', '2026-11-04'],
  [102, 'Impresora de secretaría sin conexión', 'Hardware', 'Media', 'En curso', 'Lucía', '2026-11-05'],
  [103, 'Actualización de navegador pendiente', 'Software', 'Baja', 'Resuelta', 'Pablo', '2026-11-06'],
  [104, 'Cortes intermitentes de conexión Wi-Fi', 'Redes', 'Alta', 'En curso', 'Equipo de redes', '2026-11-07'],
  [105, 'Fallo al iniciar sesión en un equipo', 'Sistemas', 'Media', 'Pendiente', 'Equipo de soporte', '2026-11-09'],
  [106, 'Solicitud de instalación de software', 'Software', 'Baja', 'Resuelta', 'Lucía', '2026-11-10']
];
const estados = ['Pendiente', 'En curso', 'Resuelta'];
const prioridades = ['Alta', 'Media', 'Baja'];
const categorias = ['Hardware', 'Software', 'Redes', 'Sistemas', 'Otros'];
const selectFields = `id, titulo, categoria, prioridad, estado, responsable, TO_CHAR(fecha, 'YYYY-MM-DD') AS fecha`;

async function initialize() {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(`CREATE TABLE IF NOT EXISTS incidencias (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      titulo VARCHAR(100) NOT NULL,
      categoria VARCHAR(20) NOT NULL,
      prioridad VARCHAR(10) NOT NULL,
      estado VARCHAR(20) NOT NULL,
      responsable VARCHAR(80) NOT NULL,
      fecha DATE NOT NULL DEFAULT CURRENT_DATE
    )`);
    // Solo crea los seis registros iniciales si la tabla aún está vacía.
    const { rows } = await client.query('SELECT COUNT(*)::integer AS cantidad FROM incidencias');
    if (rows[0].cantidad === 0) {
      for (const item of original) {
        await client.query('INSERT INTO incidencias (id, titulo, categoria, prioridad, estado, responsable, fecha) VALUES ($1,$2,$3,$4,$5,$6,$7)', item);
      }
      await client.query("SELECT setval(pg_get_serial_sequence('incidencias','id'), (SELECT MAX(id) FROM incidencias))");
    }
    await client.query('COMMIT');
  } catch(err) { await client.query('ROLLBACK'); throw err; }
  finally { client.release(); }
}
const asyncRoute = fn => (req,res,next) => Promise.resolve(fn(req,res,next)).catch(next);

app.get('/api/salud', asyncRoute(async (_req,res) => {
  await pool.query('SELECT 1');
  res.json({ estado:'ok', version: process.env.APP_VERSION || '2.0', servicio:'gestor-incidencias', baseDatos:'conectada' });
}));
app.get('/api/config', (_req,res) => res.json({ nombre: process.env.APP_NAME || 'AulaSoporte', entorno: process.env.APP_ENV || 'Demostración', version: process.env.APP_VERSION || '2.0' }));
app.get('/api/incidencias', asyncRoute(async (_req,res) => {
  const {rows} = await pool.query(`SELECT ${selectFields} FROM incidencias ORDER BY id DESC`);
  res.json(rows);
}));
app.post('/api/incidencias', asyncRoute(async (req,res) => {
  const { titulo, categoria, prioridad } = req.body || {};
  if (typeof titulo !== 'string' || titulo.trim().length < 5 || titulo.trim().length > 100 || !categorias.includes(categoria) || !prioridades.includes(prioridad)) {
    return res.status(400).json({ error:'Comprueba el título (5 a 100 caracteres), categoría y prioridad.' });
  }
  const {rows} = await pool.query(`INSERT INTO incidencias (titulo, categoria, prioridad, estado, responsable)
    VALUES ($1,$2,$3,'Pendiente','Sin asignar') RETURNING ${selectFields}`, [titulo.trim(),categoria,prioridad]);
  res.status(201).json(rows[0]);
}));
app.patch('/api/incidencias/:id', asyncRoute(async (req,res) => {
  const id = Number(req.params.id);
  if (!Number.isSafeInteger(id) || id <= 0) return res.status(404).json({ error:'Incidencia no encontrada.' });
  if (!req.body || !estados.includes(req.body.estado)) return res.status(400).json({ error:'Estado no válido.' });
  const {rows} = await pool.query(`UPDATE incidencias SET estado=$1 WHERE id=$2 RETURNING ${selectFields}`, [req.body.estado,id]);
  if (!rows.length) return res.status(404).json({ error:'Incidencia no encontrada.' });
  res.json(rows[0]);
}));
app.get('/api/estadisticas', asyncRoute(async (_req,res) => {
  const {rows} = await pool.query(`SELECT COUNT(*)::integer AS total,
    COUNT(*) FILTER (WHERE estado='Pendiente')::integer AS pendientes,
    COUNT(*) FILTER (WHERE estado='En curso')::integer AS "enCurso",
    COUNT(*) FILTER (WHERE estado='Resuelta')::integer AS resueltas FROM incidencias`);
  res.json(rows[0]);
}));
app.use('/api', (_req,res) => res.status(404).json({error:'Ruta no encontrada.'}));
app.use((err,req,res,next) => {
  console.error('Error en la aplicación:', err.message);
  res.status(500).json({error:'No se pudo completar la operación. Revisa los registros del servidor.'});
});
initialize().then(() => {
  app.listen(PORT,'0.0.0.0', () => console.log(`AulaSoporte 2.0 conectado a PostgreSQL. Escuchando en puerto ${PORT}`));
}).catch(err => {
  console.error('Error al iniciar PostgreSQL:', err.message);
  process.exit(1);
});
process.on('SIGTERM', () => { pool.end().finally(()=>process.exit(0)); });
